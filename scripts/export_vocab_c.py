"""Emit a vocab.c with the given tokenizer's pieces as C string arrays.

Usage:
    .venv/bin/python scripts/export_vocab_c.py [--tok PATH] [--out PATH]
Defaults keep the original behavior: model/tokenizer.model -> host/vocab.c
"""

import argparse
import os
import sys

import sentencepiece as spm

ROOT = os.path.join(os.path.dirname(__file__), "..")


def c_escape(s: str) -> str:
    out = []
    for ch in s.encode("utf-8"):
        if ch in (34, 63, 92):  # " ? backslash
            out.append(f"\\{chr(ch)}")
        elif 32 <= ch < 127:
            out.append(chr(ch))
        elif ch in (10, 13, 9):
            out.append(f"\\{ch}")
        else:
            out.append(f"\\{ch:03o}")
    return "".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tok", default=os.path.join(ROOT, "model", "tokenizer.model"),
                    help="trained sentencepiece BPE-512 tokenizer")
    ap.add_argument("--out", default=os.path.join(ROOT, "host", "vocab.c"),
                    help="output C source file defining sp_piece[]")
    args = ap.parse_args()

    sp = spm.SentencePieceProcessor(model_file=args.tok)
    n = sp.get_piece_size()
    lines = [
        "/* Auto-generated by scripts/export_vocab_c.py — do not edit. */",
        f"const int sp_n = {n};",
        "const char *sp_piece[] = {",
    ]
    for i in range(n):
        lines.append(f'    "{c_escape(sp.id_to_piece(i))}",')
    lines.append("};")
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {args.out} with {n} pieces ({os.path.getsize(args.out)} bytes)")


if __name__ == "__main__":
    main()
